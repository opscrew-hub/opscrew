/**
 * Keyless GitHub Actions OIDC deploy workflow for AWS targets (Feature 034, T3405, ADR 0040 D10).
 *
 * Uses `permissions: { id-token: write, contents: read }` and commit-pinned
 * `aws-actions/configure-aws-credentials` assuming the environment's least-privilege OIDC role
 * (`vars.OPSCREW_AWS_DEPLOY_ROLE_ARN`) — zero long-lived `AWS_ACCESS_KEY_ID` or
 * `AWS_SECRET_ACCESS_KEY` stored in GitHub Secrets.
 *
 * All interpolated identifiers are YAML-escaped; ECS registers a new task-definition revision
 * pinned to the newly pushed `$IMAGE_URI` before updating the service.
 */
import type { ManagedCloudRenderedFile } from "@opscrew/contracts";
import type { AwsTarget } from "@opscrew/plan-schema";

/** Commit-pinned official GitHub Actions (avoiding mutable tags). */
const ACTIONS_CHECKOUT = "actions/checkout@de0fac2e4500dabe0009e67214ff5f5447ce83dd"; // v6.0.2
const CONFIGURE_AWS_CREDENTIALS =
  "aws-actions/configure-aws-credentials@e3dd6a429d7300a6a4c196c26e071d42e0343502"; // v4.0.2
const AMAZON_ECR_LOGIN = "aws-actions/amazon-ecr-login@062b18b96a7aff071d4dc91bc00c4c1a7945b076"; // v2.0.1

/** Escapes a scalar for safe inclusion inside a double-quoted YAML string. */
function yamlString(value: string): string {
  return JSON.stringify(value);
}

export interface RenderAwsWorkflowInput {
  readonly appName: string;
  readonly environment: string;
  readonly workflowPath: string;
  readonly branch: string;
  readonly target: AwsTarget;
  readonly healthUrl?: string;
}

/** Renders the keyless OIDC GitHub Actions deploy workflow for an AWS managed target. */
export function renderAwsDeployWorkflow(input: RenderAwsWorkflowInput): ManagedCloudRenderedFile {
  const { appName, environment, branch, target } = input;
  const serviceName = `opscrew-${appName}-${environment}`;
  const deployStep =
    target.compute === "lightsail-containers"
      ? `      - name: Push image to Lightsail and deploy new version
        env:
          SERVICE_NAME: ${yamlString(serviceName)}
        run: |
          set -euo pipefail
          aws lightsail push-container-image \\
            --service-name "$SERVICE_NAME" \\
            --label app \\
            --image "$IMAGE_URI"
          LIGHTSAIL_IMG=$(aws lightsail get-container-images --service-name "$SERVICE_NAME" --query 'containerImages[0].image' --output text)
          jq -n --arg img "$LIGHTSAIL_IMG" '{app: {image: $img}}' > containers.json
          aws lightsail create-container-service-deployment \\
            --service-name "$SERVICE_NAME" \\
            --containers file://containers.json`
      : target.compute === "lambda-web"
        ? `      - name: Update Lambda Web Function revision with built image
        env:
          SERVICE_NAME: ${yamlString(serviceName)}
        run: |
          set -euo pipefail
          aws lambda update-function-code \\
            --function-name "$SERVICE_NAME" \\
            --image-uri "$IMAGE_URI"
          aws lambda wait function-updated \\
            --function-name "$SERVICE_NAME"`
        : target.compute === "ec2-compose"
          ? `      - name: Roll out container image on EC2 host via SSM Run Command
        env:
          SERVICE_NAME: ${yamlString(serviceName)}
        run: |
          set -euo pipefail
          INSTANCE_ID=$(aws ec2 describe-instances \\
            --filters "Name=tag:Name,Values=$SERVICE_NAME" "Name=instance-state-name,Values=running" \\
            --query 'Reservations[0].Instances[0].InstanceId' --output text)
          aws ssm send-command \\
            --instance-ids "$INSTANCE_ID" \\
            --document-name "AWS-RunShellScript" \\
            --parameters commands="["docker pull $IMAGE_URI && docker compose -f /opt/opscrew/compose.yaml up -d"]"`
          : `      - name: Register new ECS task definition with built image and roll out
        env:
          SERVICE_NAME: ${yamlString(serviceName)}
        run: |
          set -euo pipefail
          aws ecs describe-task-definition \\
            --task-definition "$SERVICE_NAME" \\
            --query 'taskDefinition' > td.json
          jq --arg img "$IMAGE_URI" '
            del(.taskDefinitionArn, .revision, .status, .requiresAttributes, .compatibilities, .registeredAt, .registeredBy)
            | .containerDefinitions[0].image = $img
          ' td.json > new-td.json
          NEW_TD_ARN=$(aws ecs register-task-definition --cli-input-json file://new-td.json --query 'taskDefinition.taskDefinitionArn' --output text)
          aws ecs update-service \\
            --cluster "$SERVICE_NAME" \\
            --service "$SERVICE_NAME" \\
            --task-definition "$NEW_TD_ARN"
          aws ecs wait services-stable \\
            --cluster "$SERVICE_NAME" \\
            --services "$SERVICE_NAME"`;

  const content = `# Generated by OpsCrew (feature 034): keyless GitHub Actions OIDC deploy to AWS (${target.compute}).
# Uses short-lived OIDC tokens (id-token: write) — zero long-lived AWS keys stored in GitHub Secrets.
name: ${yamlString(`OpsCrew Deploy AWS (${appName} / ${environment})`)}

on:
  push:
    branches: [${yamlString(branch)}]
  workflow_dispatch:

concurrency:
  group: ${yamlString(`opscrew-aws-${appName}-${environment}`)}
  cancel-in-progress: false

permissions:
  id-token: write
  contents: read

jobs:
  deploy:
    runs-on: ubuntu-latest
    environment: ${yamlString(environment)}
    steps:
      - name: Checkout repository
        uses: ${ACTIONS_CHECKOUT}

      - name: Configure short-lived AWS credentials via GitHub OIDC
        uses: ${CONFIGURE_AWS_CREDENTIALS}
        with:
          role-to-assume: \${{ vars.OPSCREW_AWS_DEPLOY_ROLE_ARN }}
          aws-region: ${yamlString(target.region)}

      - name: Log in to Amazon ECR
        id: ecr
        uses: ${AMAZON_ECR_LOGIN}

      - name: Build and push immutable container image
        env:
          ECR_REGISTRY: \${{ steps.ecr.outputs.registry }}
          ECR_REPOSITORY: ${yamlString(serviceName)}
          IMAGE_TAG: \${{ github.sha }}
        run: |
          set -euo pipefail
          IMAGE_URI="$ECR_REGISTRY/$ECR_REPOSITORY:$IMAGE_TAG"
          docker build -t "$IMAGE_URI" .
          docker push "$IMAGE_URI"
          echo "IMAGE_URI=$IMAGE_URI" >> "$GITHUB_ENV"

${deployStep}
`;

  return {
    path: input.workflowPath,
    content,
    kind: "workflow",
  };
}
