/**
 * Keyless GitHub Actions OIDC deploy workflow for AWS targets (Feature 034, T3405, ADR 0040 D10).
 *
 * Uses `permissions: { id-token: write, contents: read }` and commit-pinned
 * `aws-actions/configure-aws-credentials` assuming the environment's least-privilege OIDC role
 * (`vars.OPSCREW_AWS_DEPLOY_ROLE_ARN`) — zero long-lived `AWS_ACCESS_KEY_ID` or
 * `AWS_SECRET_ACCESS_KEY` stored in GitHub Secrets.
 */
import type { ManagedCloudRenderedFile } from "@opscrew/contracts";
import type { AwsTarget } from "@opscrew/plan-schema";

/** Commit-pinned official GitHub Actions (avoiding mutable tags). */
const ACTIONS_CHECKOUT = "actions/checkout@de0fac2e4500dabe0009e67214ff5f5447ce83dd"; // v6.0.2
const CONFIGURE_AWS_CREDENTIALS =
  "aws-actions/configure-aws-credentials@e3dd6a429d7300a6a4c196c26e071d42e0343502"; // v4.0.2
const AMAZON_ECR_LOGIN = "aws-actions/amazon-ecr-login@062b18b96a7aff071d4dc91bc00c4c1a7945b076"; // v2.0.1

export interface RenderAwsWorkflowInput {
  readonly appName: string;
  readonly environment: string;
  readonly workflowPath: string;
  readonly branch: string;
  readonly target: AwsTarget;
  readonly healthUrl?: string;
}

/** Renders the keyless OIDC GitHub Actions deploy workflow for an AWS managed target. */
export function renderAwsDeployWorkflow(input: RenderAwsWorkflowInput): ManagedCloudRenderedFile {
  const { appName, environment, branch, target } = input;
  const serviceName = `opscrew-${appName}-${environment}`;
  const deployStep =
    target.compute === "lightsail-containers"
      ? `      - name: Deploy new Lightsail container version
        run: |
          set -euo pipefail
          aws lightsail create-container-service-deployment \\
            --service-name "${serviceName}" \\
            --containers "{\\"app\\":{\\"image\\":\\"$IMAGE_URI\\"}}"`
      : target.compute === "lambda-web"
        ? `      - name: Publish Lambda Web Function revision
        run: |
          set -euo pipefail
          echo "Deploying Lambda Web Function revision for ${serviceName} ($IMAGE_URI)"`
        : `      - name: Roll out ECS Fargate service and wait for stability
        run: |
          set -euo pipefail
          aws ecs update-service \\
            --cluster "${serviceName}" \\
            --service "${serviceName}" \\
            --force-new-deployment
          aws ecs wait services-stable \\
            --cluster "${serviceName}" \\
            --services "${serviceName}"`;

  const content = `# Generated by OpsCrew (feature 034): keyless GitHub Actions OIDC deployment to AWS.
name: OpsCrew Deploy (${appName} / ${environment})

on:
  push:
    branches: ["${branch}"]
  workflow_dispatch:

concurrency:
  group: opscrew-aws-${appName}-${environment}
  cancel-in-progress: false

permissions:
  id-token: write
  contents: read

jobs:
  deploy:
    name: Build and deploy to AWS (${target.region})
    runs-on: ubuntu-latest
    environment: ${environment}
    steps:
      - name: Checkout repository
        uses: ${ACTIONS_CHECKOUT}

      - name: Configure AWS credentials via GitHub OIDC (keyless)
        uses: ${CONFIGURE_AWS_CREDENTIALS}
        with:
          role-to-assume: \${{ vars.OPSCREW_AWS_DEPLOY_ROLE_ARN }}
          aws-region: ${target.region}

      - name: Login to Amazon ECR
        id: ecr
        uses: ${AMAZON_ECR_LOGIN}

      - name: Build and push immutable image
        id: build
        env:
          ECR_REGISTRY: \${{ steps.ecr.outputs.registry }}
          ECR_REPOSITORY: ${serviceName}
          IMAGE_TAG: \${{ github.sha }}
        run: |
          set -euo pipefail
          IMAGE_URI="$ECR_REGISTRY/$ECR_REPOSITORY:$IMAGE_TAG"
          docker build -t "$IMAGE_URI" .
          docker push "$IMAGE_URI"
          echo "image_uri=$IMAGE_URI" >> "$GITHUB_OUTPUT"

${deployStep}
        env:
          IMAGE_URI: \${{ steps.build.outputs.image_uri }}
`;

  return {
    path: input.workflowPath,
    content,
    kind: "workflow",
  };
}
