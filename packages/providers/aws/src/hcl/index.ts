function renderDatabaseTf(ctx: RenderAwsHclContext): string | undefined {
  const db = ctx.target.components.database;
  if (
    db === undefined ||
    db.service === "existing-database" ||
    db.config.externalManaged === true
  ) {
    return undefined;
  }
  const publiclyAccessible = ctx.target.guardrails.privateDatabase ? "false" : "true";
  const storageEncrypted = ctx.target.guardrails.encryptionAtRest ? "true" : "false";
  const backupDays = ctx.target.guardrails.automatedBackups ? 7 : 0;
  const instanceClass = hclString(
    typeof db.config.instanceClass === "string" ? db.config.instanceClass : "db.t4g.micro",
  );
  const multiAz = db.config.multiAz === true ? "true" : "false";
  const deletionProtection = ctx.target.preset === "production-ha" ? "true" : "false";
  const isMysql = db.service.includes("mysql");
  const engine = isMysql ? "mysql" : "postgres";
  const dbPort = isMysql ? 3306 : 5432;

  return `# Private managed database (publicly_accessible = ${publiclyAccessible}, encrypted = ${storageEncrypted}).
resource "aws_db_subnet_group" "app" {
  name       = "opscrew-\${var.app_name}-\${var.environment}-db"
  subnet_ids = local.private_subnet_ids
}

resource "aws_security_group" "db" {
  name        = "opscrew-\${var.app_name}-\${var.environment}-db"
  description = "Private database access from app security group only."
  vpc_id      = local.vpc_id

  ingress {
    description     = "Database access from app compute security group only"
    from_port       = ${dbPort}
    to_port         = ${dbPort}
    protocol        = "tcp"
    security_groups = [aws_security_group.app.id]
  }
}

resource "aws_db_instance" "app" {
  identifier                  = "opscrew-\${var.app_name}-\${var.environment}"
  engine                      = "${engine}"
  instance_class              = "${instanceClass}"
  allocated_storage           = 20
  storage_type                = "gp3"
  storage_encrypted           = ${storageEncrypted}
  multi_az                    = ${multiAz}
  publicly_accessible         = ${publiclyAccessible}
  deletion_protection         = ${deletionProtection}
  backup_retention_period     = ${backupDays}
  db_subnet_group_name        = aws_db_subnet_group.app.name
  vpc_security_group_ids      = [aws_security_group.db.id]
  manage_master_user_password = true
  skip_final_snapshot         = false
  final_snapshot_identifier   = "opscrew-\${var.app_name}-\${var.environment}-final-\${formatdate("YYYYMMDDhhmmss", timestamp())}"

  lifecycle {
    ignore_changes = [final_snapshot_identifier]
  }
}
`;
}

function renderAcmTf(ctx: RenderAwsHclContext): string | undefined {
  if (ctx.domain === undefined || ctx.domain.trim() === "") return undefined;
  const domain = hclString(ctx.domain.trim());
  return `# Public ACM certificate with DNS-01 validation (free; never provisions $400/mo Private CA).
# When Cloudflare manages DNS, OpsCrew writes validation CNAMEs with proxied = false (DNS only).
resource "aws_acm_certificate" "app" {
  domain_name       = "${domain}"
  validation_method = "DNS"

  lifecycle {
    create_before_destroy = true
  }
}
`;
}

function renderStorageTf(ctx: RenderAwsHclContext): string | undefined {
  if (ctx.target.components.storage === undefined) return undefined;
  return `# Private S3 bucket with Block Public Access and AES-256 encryption at rest (served via CloudFront OAC).
resource "aws_s3_bucket" "uploads" {
  bucket_prefix = "opscrew-\${var.app_name}-\${var.environment}-"
}

resource "aws_s3_bucket_public_access_block" "uploads" {
  bucket                  = aws_s3_bucket.uploads.id
  block_public_acls       = true
  block_public_policy     = true
  ignore_public_acls      = true
  restrict_public_buckets = true
}

resource "aws_s3_bucket_server_side_encryption_configuration" "uploads" {
  bucket = aws_s3_bucket.uploads.id

  rule {
    apply_server_side_encryption_by_default {
      sse_algorithm = "AES256"
    }
  }
}

resource "aws_s3_bucket_versioning" "uploads" {
  bucket = aws_s3_bucket.uploads.id

  versioning_configuration {
    status = "Enabled"
  }
}
`;
}

function renderSecretsTf(ctx: RenderAwsHclContext): string {
  const sec = ctx.target.components.secrets;
  if (sec?.service === "secrets-manager-bundle") {
    return `# Secret shell ONLY — real secret values are written out-of-band by OpsCrew's AWS connector after approval,
# never embedded in Terraform HCL or .tfstate (Constitution IV / research R5).
resource "aws_secretsmanager_secret" "app_env" {
  name        = "opscrew/\${var.app_name}/\${var.environment}/app-env"
  description = "Bundled runtime environment for \${var.app_name} (\${var.environment}). Populated out-of-band."
}
`;
  }
  return `# SSM Parameter Store Standard ($0/mo): OpsCrew writes SecureString values out-of-band after approval
# so plaintext secret values never enter Terraform HCL or .tfstate (Constitution IV / research R5).
locals {
  ssm_parameter_prefix = "/opscrew/\${var.app_name}/\${var.environment}"
}
`;
}

function renderObservabilityTf(ctx: RenderAwsHclContext): string {
  const retention = ctx.target.observability.logsRetentionDays;
  const alarms = ctx.target.observability.alarms
    ? `
resource "aws_sns_topic" "alerts" {
  name = "opscrew-\${var.app_name}-\${var.environment}-alerts"
}
`
    : "";

  return `# Explicit CloudWatch Logs retention prevents unbounded log storage costs (research R7).
resource "aws_cloudwatch_log_group" "app" {
  name              = "/opscrew/\${var.app_name}/\${var.environment}/app"
  retention_in_days = ${retention}
}
${alarms}`;
}

function renderOutputsTf(ctx: RenderAwsHclContext): string {
  const hasDomain = ctx.domain !== undefined && ctx.domain.trim() !== "";
  const acmOutput = hasDomain
    ? `
output "acm_validation_records" {
  description = "DNS-01 validation CNAME records for ACM (must be proxied = false on Cloudflare)."
  value = [
    for dvo in aws_acm_certificate.app.domain_validation_options : {
      name  = dvo.resource_record_name
      type  = dvo.resource_record_type
      value = dvo.resource_record_value
    }
  ]
}
`
    : "";

  return `output "deploy_role_arn" {
  description = "GitHub Actions OIDC IAM role ARN for keyless deployments."
  value       = aws_iam_role.github_deploy.arn
}

output "ecr_repository_url" {
  description = "ECR repository URL for app container images."
  value       = aws_ecr_repository.app.repository_url
}

output "log_group_name" {
  description = "CloudWatch Logs group name for opscrew logs."
  value       = aws_cloudwatch_log_group.app.name
}
${ctx.target.components.storage !== undefined ? `\noutput "uploads_bucket_name" {\n  value = aws_s3_bucket.uploads.bucket\n}\n` : ""}${acmOutput}`;
}

/** Renders the complete set of vendored, standalone AWS HCL files under `ctx.infraDir`. */
export function renderAwsHcl(ctx: RenderAwsHclContext): ManagedCloudRenderedFile[] {
  const dir = ctx.infraDir.replace(/\\/g, "/").replace(/\/+$/, "");
  const files: ManagedCloudRenderedFile[] = [
    { path: `${dir}/providers.tf`, content: renderProvidersTf(ctx), kind: "iac" },
    { path: `${dir}/variables.tf`, content: renderVariablesTf(ctx), kind: "iac" },
    { path: `${dir}/vpc.tf`, content: renderVpcTf(ctx), kind: "iac" },
    { path: `${dir}/iam-oidc.tf`, content: renderIamOidcTf(ctx), kind: "iac" },
    { path: `${dir}/compute.tf`, content: renderComputeTf(ctx), kind: "iac" },
    { path: `${dir}/secrets.tf`, content: renderSecretsTf(ctx), kind: "iac" },
    { path: `${dir}/observability.tf`, content: renderObservabilityTf(ctx), kind: "iac" },
    { path: `${dir}/outputs.tf`, content: renderOutputsTf(ctx), kind: "iac" },
  ];

  const dbTf = renderDatabaseTf(ctx);
  if (dbTf !== undefined) {
    files.push({ path: `${dir}/database.tf`, content: dbTf, kind: "iac" });
  }
  const acmTf = renderAcmTf(ctx);
  if (acmTf !== undefined) {
    files.push({ path: `${dir}/acm.tf`, content: acmTf, kind: "iac" });
  }
  const storageTf = renderStorageTf(ctx);
  if (storageTf !== undefined) {
    files.push({ path: `${dir}/storage.tf`, content: storageTf, kind: "iac" });
  }

  return files;
}
