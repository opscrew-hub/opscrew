/**
 * Vendored readable AWS OpenTofu/Terraform HCL renderer (Feature 034, T3405, ADR 0040 D10–D11).
 *
 * Renders pinned `hashicorp/aws ~> 6.0` HCL files into `infra/` so users can inspect or run
 * `tofu` without OpsCrew (Constitution II):
 * - All interpolated strings escaped via `hclString()` (zero HCL template/quote injection).
 * - Zero plaintext secrets in HCL or Terraform state (`aws_secretsmanager_secret` / SSM metadata shells only).
 * - Strict GitHub Actions OIDC trust policy (`StringEquals` on `aud` and exact repo/environment `sub`,
 *   matching workflow `environment:` and supporting July 2026 immutable numeric org/repo IDs; zero wildcards).
 * - Working VPC/existing-VPC locals, app egress + app->DB ingress security groups, lean public-subnet
 *   Fargate (`assign_public_ip = true` + strict SG per ADR 0040 D9), per-compute renderers (refusing
 *   unsupported kinds), ACM certificate + `acm_validation_records` output for Cloudflare DNS-01,
 *   private encrypted databases, S3 Block Public Access + SSE, and explicit CloudWatch `retention_in_days`.
 */
import type { ManagedCloudRenderedFile } from "@opscrew/contracts";
import type { AwsTarget } from "@opscrew/plan-schema";
import { AwsProviderError } from "../connector";

/** Pinned AWS Terraform provider constraint (verified v6.74.0 in `specs/034-aws/research.md` R5). */
export const AWS_PROVIDER_VERSION = "~> 6.0" as const;

/** Shared canonical RDS instance identifier used by HCL rendering and snapshot/drill operations. */
export function awsDbIdentifier(appName: string, environment: string): string {
  return `opscrew-${appName}-${environment}`;
}

/**
 * Escapes an arbitrary string for safe placement inside a double-quoted HCL string literal,
 * neutralizing quotes, backslashes, newlines, `${...}` interpolations, and `%{...}` directives.
 */
export function hclString(value: string): string {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t")
    .replace(/\$\{/g, () => "$${")
    .replace(/%\{/g, () => "%%{");
}

export interface RenderAwsHclContext {
  readonly appName: string;
  readonly environment: string;
  readonly infraDir: string;
  readonly target: AwsTarget;
  readonly domain?: string;
  readonly github: {
    readonly owner: string;
    readonly repo: string;
    /** Optional numeric GitHub IDs for July 2026+ immutable OIDC subject claims. */
    readonly ownerId?: number;
    readonly repoId?: number;
    readonly environmentName?: string;
    readonly branch?: string;
  };
  /** Optional `floci` / custom endpoint URL (e.g., `http://localhost:4566`) for local emulator tests. */
  readonly endpointUrl?: string;
  /**
   * Whether to create `aws_iam_openid_connect_provider.github` (default `false` — uses a `data`
   * lookup so existing AWS accounts do not fail with `EntityAlreadyExists`).
   */
  readonly createOidcProvider?: boolean;
}

/** Builds the exact, wildcard-free GitHub OIDC `sub` claim (research R4). */
export function githubOidcSubject(github: RenderAwsHclContext["github"]): string {
  const repoSlug =
    github.ownerId !== undefined && github.repoId !== undefined
      ? `${github.owner}@${github.ownerId}/${github.repo}@${github.repoId}`
      : `${github.owner}/${github.repo}`;
  if (github.environmentName !== undefined) {
    return `repo:${repoSlug}:environment:${github.environmentName}`;
  }
  return `repo:${repoSlug}:ref:refs/heads/${github.branch ?? "main"}`;
}

