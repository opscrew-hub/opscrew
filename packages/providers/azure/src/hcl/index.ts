/**
 * Escapes an arbitrary string into a valid double-quoted HCL string literal.
 * Uses replacer callbacks for `$${` and `%%{` so JS `String.prototype.replace` never collapses `$$`.
 */
export function hclString(value: string): string {
  const escaped = value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t")
    .replace(/\$\{/g, () => "$${")
    .replace(/%\{/g, () => "%%{");
  return `"${escaped}"`;
}

/** Builds an exact, wildcard-free GitHub OIDC `sub` claim pinned to repo + environment. */
export function azureGithubOidcSubject(github: RenderAzureHclContext["github"]): string {
  const env = github.environmentName?.trim();
  if (env !== undefined && env.length > 0) {
    return `repo:${github.owner}/${github.repo}:environment:${env}`;
  }
  return `repo:${github.owner}/${github.repo}:ref:refs/heads/${github.branch ?? "main"}`;
}

/** Sanitizes an Azure Storage Account name (3-24 lowercase alphanumerics, no hyphens). */
export function azureStorageAccountName(appName: string, environment: string): string {
  const cleaned = `st${appName}${environment}`.toLowerCase().replace(/[^a-z0-9]/g, "");
  return cleaned.slice(0, 24).padEnd(3, "0");
}

