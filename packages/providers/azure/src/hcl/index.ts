function renderOutputsTf(ctx: RenderAzureHclContext): string {
  const hasDomain = ctx.domain !== undefined && ctx.domain.length > 0;
  const verificationExpr =
    ctx.target.compute === "container-apps"
      ? "azurerm_container_app.app.custom_domain_verification_id"
      : ctx.target.compute === "app-service"
        ? "azurerm_linux_web_app.app.custom_domain_verification_id"
        : undefined;

  const asuidOutput =
    hasDomain && verificationExpr !== undefined
      ? `
output "asuid_validation_records" {
  description = "Custom-domain TXT verification record for Azure (must be DNS-only / proxied = false on Cloudflare)."
  sensitive   = true
  value = [
    {
      name  = ${hclString(`asuid.${ctx.domain}`)}
      value = ${verificationExpr}
    }
  ]
}
`
      : `
output "asuid_validation_records" {
  description = "Custom-domain TXT verification records (empty when no custom domain is configured)."
  value       = []
}
`;

  return `output "resource_group_name" {
  value = azurerm_resource_group.app.name
}

output "deploy_client_id" {
  value = azurerm_user_assigned_identity.deploy.client_id
}

output "app_fqdn" {
  value = local.app_fqdn
}

output "key_vault_uri" {
  value = azurerm_key_vault.app.vault_uri
}

output "log_analytics_workspace_id" {
  value = azurerm_log_analytics_workspace.app.workspace_id
}
${asuidOutput}`;
}

export function renderAzureHcl(ctx: RenderAzureHclContext): readonly ManagedCloudRenderedFile[] {
  const files: ManagedCloudRenderedFile[] = [
    { path: "versions.tf", content: renderVersionsTf(), kind: "iac" },
    { path: "variables.tf", content: renderVariablesTf(ctx), kind: "iac" },
    { path: "main.tf", content: renderMainTf(ctx), kind: "iac" },
    { path: "network.tf", content: renderNetworkTf(ctx), kind: "iac" },
    { path: "iam.tf", content: renderIamTf(ctx), kind: "iac" },
    { path: "compute.tf", content: renderComputeTf(ctx), kind: "iac" },
    { path: "secrets.tf", content: renderSecretsTf(ctx), kind: "iac" },
  ];

  const db = renderDatabaseTf(ctx);
  if (db !== undefined) files.push({ path: "database.tf", content: db, kind: "iac" });

  const cache = renderCacheTf(ctx);
  if (cache !== undefined) files.push({ path: "cache.tf", content: cache, kind: "iac" });

  const storage = renderStorageTf(ctx);
  if (storage !== undefined) files.push({ path: "storage.tf", content: storage, kind: "iac" });

  const edge = renderEdgeTf(ctx);
  if (edge !== undefined) files.push({ path: "edge.tf", content: edge, kind: "iac" });

  files.push({ path: "outputs.tf", content: renderOutputsTf(ctx), kind: "iac" });
  return files;
}
