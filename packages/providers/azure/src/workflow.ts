/**
 * Keyless GitHub Actions OIDC deploy workflow renderer for Microsoft Azure (Feature 038, T3803).
 *
 * Uses `azure/login@v2` with Federated Identity Credentials (`id-token: write`, ZERO stored client
 * secrets) and pins the job's GitHub `environment:` to match `azurerm_federated_identity_credential`'s
 * `subject = "repo:<owner>/<repo>:environment:<env>"`.
 */
import type { ManagedCloudRenderedFile } from "@opscrew/contracts";
import type { AzureTarget } from "@opscrew/plan-schema";

export interface RenderAzureWorkflowInput {
  readonly appName: string;
  readonly environment: string;
  readonly workflowPath: string;
  readonly target: AzureTarget;
  readonly branch: string;
  readonly clientIdVar?: string;
  readonly tenantIdVar?: string;
  readonly subscriptionIdVar?: string;
}

/** Escapes a scalar for safe inclusion inside YAML double quotes. */
function yamlString(value: string): string {
  return `"${value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t")}"`;
}

/** Validates a GitHub Actions variable identifier so untrusted text cannot break `${{ vars.* }}`. */
function safeVarName(name: string, fallback: string): string {
  return /^[A-Z][A-Z0-9_]*$/.test(name) ? name : fallback;
}

export function renderAzureDeployWorkflow(
  input: RenderAzureWorkflowInput,
): ManagedCloudRenderedFile {
  const clientIdVar = safeVarName(input.clientIdVar ?? "AZURE_CLIENT_ID", "AZURE_CLIENT_ID");
  const tenantIdVar = safeVarName(input.tenantIdVar ?? "AZURE_TENANT_ID", "AZURE_TENANT_ID");
  const subscriptionIdVar = safeVarName(
    input.subscriptionIdVar ?? "AZURE_SUBSCRIPTION_ID",
    "AZURE_SUBSCRIPTION_ID",
  );
  const rgName = `rg-opscrew-${input.appName}-${input.environment}`;
  const appResourceName = `opscrew-${input.appName}-${input.environment}`;

  let deployStep: string;
  if (input.target.compute === "app-service") {
    deployStep = `      - name: Deploy container image to Azure App Service
        env:
          RG_NAME: ${yamlString(rgName)}
          WEBAPP_NAME: ${yamlString(appResourceName)}
          IMAGE_REF: \${{ steps.build.outputs.image }}
        run: |
          az webapp config container set \\
            --resource-group "$RG_NAME" \\
            --name "$WEBAPP_NAME" \\
            --container-image-name "$IMAGE_REF"
          az webapp restart --resource-group "$RG_NAME" --name "$WEBAPP_NAME"`;
  } else if (input.target.compute === "vm-compose") {
    deployStep = `      - name: Trigger zero-secret VM Compose update via Run Command
        env:
          RG_NAME: ${yamlString(rgName)}
          VM_NAME: ${yamlString(appResourceName)}
          IMAGE_REF: \${{ steps.build.outputs.image }}
        run: |
          az vm run-command invoke \\
            --resource-group "$RG_NAME" \\
            --name "$VM_NAME" \\
            --command-id RunShellScript \\
            --scripts "docker pull '$IMAGE_REF' && docker compose -f /opt/opscrew/compose.yml up -d"`;
  } else {
    deployStep = `      - name: Deploy container revision to Azure Container Apps
        env:
          RG_NAME: ${yamlString(rgName)}
          CONTAINER_APP: ${yamlString(appResourceName)}
          IMAGE_REF: \${{ steps.build.outputs.image }}
        run: |
          az containerapp update \\
            --resource-group "$RG_NAME" \\
            --name "$CONTAINER_APP" \\
            --image "$IMAGE_REF"`;
  }

  const content = `# Generated by OpsCrew (@opscrew/provider-azure, Feature 038)
# Keyless OIDC deployment: zero static Azure client secrets stored in GitHub.
name: ${yamlString(`Deploy ${input.appName} (${input.environment}) to Azure`)}

on:
  push:
    branches:
      - ${yamlString(input.branch)}
  workflow_dispatch:

permissions:
  id-token: write
  contents: read
  packages: write

concurrency:
  group: ${yamlString(`opscrew-azure-${input.appName}-${input.environment}`)}
  cancel-in-progress: false

jobs:
  deploy:
    runs-on: ubuntu-latest
    environment: ${yamlString(input.environment)}
    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Log in to GitHub Container Registry
        uses: docker/login-action@v3
        with:
          registry: ghcr.io
          username: \${{ github.actor }}
          password: \${{ secrets.GITHUB_TOKEN }}

      - name: Build and push container image
        id: build
        env:
          IMAGE_NAME: ghcr.io/\${{ github.repository }}
        run: |
          IMAGE_LOWER=$(echo "$IMAGE_NAME" | tr '[:upper:]' '[:lower:]')
          IMAGE_TAG="$IMAGE_LOWER:\${{ github.sha }}"
          docker build -t "$IMAGE_TAG" .
          docker push "$IMAGE_TAG"
          echo "image=$IMAGE_TAG" >> "$GITHUB_OUTPUT"

      - name: Authenticate to Azure via GitHub OIDC (keyless)
        uses: azure/login@v2
        with:
          client-id: \${{ vars.${clientIdVar} }}
          tenant-id: \${{ vars.${tenantIdVar} }}
          subscription-id: \${{ vars.${subscriptionIdVar} }}

${deployStep}
`;

  return {
    path: input.workflowPath,
    content,
    kind: "workflow",
  };
}
