import type { DeployPlan, GiteaSettings } from "@opscrew/plan-schema";
import { edgeProxy } from "../edge";
import { nginxSite } from "../edge/nginx";
import { openlitespeedSite } from "../edge/openlitespeed";
import type { SiteContext } from "../runtime";
import { caddySite } from "../runtime/services";
import { tunnelMode } from "../tunnel";
import { GITEA_EDGE_ALIAS, GITEA_UPSTREAM } from "./compose";

/** Site file name stem in `/srv/edge/sites/` for self-hosted Gitea. */
export const GITEA_SITE_NAME = GITEA_EDGE_ALIAS;

/** Maximum HTTP body size (in MB) allowed for Git pushes & LFS uploads over HTTPS. */
export const GITEA_MAX_BODY_MB = 512;

export interface GiteaProxyFile {
  /** File name inside `/srv/edge/sites/` (for example `opscrew-gitea.caddy`). */
  filename: string;
  /** Rendered reverse proxy configuration content. */
  content: string;
}

/**
 * Renders the reverse proxy site file(s) for self-hosted Gitea under `/srv/edge/sites/`, matching
 * the server's chosen edge proxy (`caddy`, `nginx`, or `openlitespeed`). Routes `gitea.hostname`
 * to `opscrew-gitea:3000` over `opscrew-edge` with HTTPS, HSTS, baseline security headers, and
 * WebSocket / large Git push support.
 */
export function renderGiteaProxySite(
  plan: DeployPlan,
  gitea: GiteaSettings,
  ctx: Pick<SiteContext, "acmeEmail" | "cloudflareRanges"> = {},
): GiteaProxyFile[] {
  const proxy = edgeProxy(plan);
  const mode = tunnelMode(plan) ? "tunnel" : "direct";
  const hosts = [gitea.hostname];
  const header = `# Generated by OpsCrew for self-hosted Gitea (${gitea.hostname}); never edit by hand.\n`;

  if (proxy === "caddy") {
    const lines = caddySite({
      mode,
      hosts,
      upstream: GITEA_UPSTREAM,
      acmeEmail: ctx.acmeEmail,
      realIp: (ctx.cloudflareRanges?.length ?? 0) > 0,
    });
    return [{ filename: `${GITEA_SITE_NAME}.caddy`, content: `${header}${lines.join("\n")}` }];
  }

  if (proxy === "nginx") {
    const lines = nginxSite({
      app: GITEA_SITE_NAME,
      mode,
      hosts,
      maxBodyMb: GITEA_MAX_BODY_MB,
      realIpFrom: ctx.cloudflareRanges,
      upstream: GITEA_UPSTREAM,
    });
    return [{ filename: `${GITEA_SITE_NAME}.conf`, content: `${header}${lines.join("\n")}` }];
  }

  const files = openlitespeedSite({
    app: GITEA_SITE_NAME,
    mode,
    hosts,
    upstream: { name: GITEA_EDGE_ALIAS, address: GITEA_UPSTREAM },
  });
  return Object.entries(files).map(([filename, lines]) => ({
    filename,
    content: `${header}${lines.join("\n")}`,
  }));
}
